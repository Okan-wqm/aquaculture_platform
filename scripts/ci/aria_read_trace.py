#!/usr/bin/env python3
"""Trace what the kernel lane's Python reads, and fail it on an off-surface read (ARIA-HIGH-602).

WHY THIS EXISTS. The required `aria-kernel` check runs its `suite`, `lane` and
`state` jobs only when a PR touches the kernel surface
(`.github/manifests/aria-kernel-surface.json`). A job can still READ tracked
files the surface does not name — a test that opens product code, a helper
that walks a directory it was never given — and a PR changing only what it
read would skip the job and pass the required check. The workflow layer is
held by `aria-kernel/tests/test_kernel_surface.py`; this module holds the run
time: every file read the traced jobs' Python makes must lie on the surface
or the job goes red naming the path.

TWO VERBS.

`install --trace-dir D`
  Writes a `usercustomize.py` into this interpreter's user site. The file
  runs THIS module's code in a module object named `aria_read_trace_hook`
  (compile + exec of the file, so `sys.path` is never touched and no import
  machinery module is loaded);
  the module then adds the audit hook below when `ARIA_READ_TRACE_DIR` and
  `GITHUB_WORKSPACE` are both set, and does nothing otherwise. The user site
  is the carrier because lane steps set `PYTHONPATH` inline, which would hide
  a `PYTHONPATH`-ridden hook; the arbiter probe measured the user site
  surviving that override and reaching child interpreters. It also appends
  `ARIA_READ_TRACE_DIR=D` to `$GITHUB_ENV`, so every later step in the job is
  traced without each step saying so.

`verify --trace-dir D --manifest M`
  Run it as `python3 -I` (isolated: no user site, so it does not trace
  itself). tracked = `git ls-files`; covered = `git ls-files -- <the
  manifest's :(glob) pathspecs>`; the reads come from every `trace-<pid>.tsv`
  under D. Any tracked read outside the coverage fails the run, naming the
  paths grouped by directory, with the remedy. Directory listings are
  reported but do not gate (a file read under a listed directory is caught as
  a file read); untracked reads do not gate (they are not PR inputs); a
  corrupt trace line fails the run rather than passing silently.

WHAT IT DOES NOT SEE, NAMED. Reads by node (`npm ci`, jest, ts-node), by
interpreters started with `-I` or `-s` (they never load the user site), and
by anything inside a sandbox that drops the user site. The workflow layer's
static check covers the workflow side of that; a gap that slips through goes
red on the next kernel run, with the path named.

Standard library only, so `python3 -I` can run it on a bare Actions host.
"""

# NO MODULE-LEVEL IMPORT BEYOND `os` AND `sys`. This file is also the audit
# hook every traced interpreter loads at startup, and an observer that loads a
# module changes the program it observes: the genesis adapter launcher refuses
# the import of any module not already loaded, so a hook that pulled in
# `subprocess` handed seven bypass spellings a preloaded module (run
# 39744490984, shard 9). Both are loaded before `site` runs; the verbs import
# what they need when they run, in their own process. No `from __future__`
# either (it imports `__future__`): annotations naming lazily imported types
# are strings.
import os
import sys

_MARKER = "# aria-kernel read tracer (ARIA-HIGH-602)"
_HOOK_MODULE = "aria_read_trace_hook"
_READ_KINDS = ("read", "git")
_LIST_KIND = "list"

_USERCUSTOMIZE = f'''{_MARKER}
# Generated by scripts/ci/aria_read_trace.py install; deleting it disables tracing.
import sys

# The hook is compiled and run in a bare module object rather than loaded through
# importlib.util: a stock interpreter (Actions' hosted CPython) has not
# imported importlib.util at startup, and the hook may load no module the
# traced program did not.
if "{_HOOK_MODULE}" not in sys.modules:
    _aria_module = type(sys)("{_HOOK_MODULE}")
    _aria_module.__file__ = {{hook_path!r}}
    sys.modules["{_HOOK_MODULE}"] = _aria_module
    with open({{hook_path!r}}, encoding="utf-8") as _aria_source:
        exec(compile(_aria_source.read(), {{hook_path!r}}, "exec"), _aria_module.__dict__)
    del _aria_module, _aria_source
'''


# A trace line is `kind<TAB>path<LF>`; a name may carry a tab or a line break
# (a git argv token such as a `commit -m` body naming a `Closes:` path is
# recorded as a candidate path too), so the path is percent-escaped for exactly
# the escape character and the three separators. str.replace only: the hook
# loads no module. `_unescape` reverses it in one pass, so it is lossless.
_ESCAPES = (("%", "%25"), ("\t", "%09"), ("\n", "%0A"), ("\r", "%0D"))


def _escape(path: str) -> str:
    for raw, escaped in _ESCAPES:
        path = path.replace(raw, escaped)
    return path


def _unescape(field: str) -> str:
    import re

    table = {escaped: raw for raw, escaped in _ESCAPES}
    return re.sub(r"%(?:25|09|0A|0D)", lambda match: table[match.group(0)], field)


class _TraceState:
    """The audit hook's mutable state. The hook never raises and never re-enters."""

    def __init__(self, workspace: str, trace_dir: str) -> None:
        self.workspace = os.path.realpath(workspace)
        self.trace_dir = trace_dir
        self.seen: set[str] = set()
        self.in_hook = False

    # -- recording ---------------------------------------------------------

    def _record(self, raw: object, kind: str, base: "str | None" = None) -> None:
        try:
            if isinstance(raw, bytes):
                raw = os.fsdecode(raw)
            if not isinstance(raw, str) or not raw:
                return
            # A relative name resolves against the directory it is used in:
            # the caller's cwd for an open, the child's cwd for a git run.
            candidate = raw if os.path.isabs(raw) else os.path.join(base or os.getcwd(), raw)
            candidate = os.path.abspath(candidate)
            # Containment before any syscall: almost every audited open is
            # interpreter startup reading its own stdlib, outside the workspace.
            if candidate != self.workspace and not candidate.startswith(self.workspace + os.sep):
                return
            if candidate in self.seen:
                return
            self.seen.add(candidate)
            if os.path.isdir(candidate):
                entry_kind = _LIST_KIND
            else:
                entry_kind = kind
            relative = os.path.relpath(candidate, self.workspace).replace(os.sep, "/")
            trace_file = os.path.join(self.trace_dir, f"trace-{os.getpid()}.tsv")
            with open(trace_file, "a", encoding="utf-8") as handle:
                handle.write(f"{entry_kind}\t{_escape(relative)}\n")
        except Exception:
            # An audit hook that raises would break the program it observes.
            pass

    def _record_open(self, args: tuple) -> None:
        mode = args[1] if len(args) > 1 else None
        if isinstance(mode, str):
            reads = "r" in mode  # io.open: "r", "rb", "r+"; "w"/"a"/"x" never carry r
        elif isinstance(mode, int):
            reads = (mode & 0x3) == 0  # os.open flags: O_WRONLY=1, O_RDWR=2
        else:
            reads = True
        if reads:
            self._record(args[0], "read")

    def _record_git(self, popen_args: tuple) -> None:
        # CPython audits subprocess.Popen as (executable, argv, cwd, env); a
        # bare sequence is accepted too, for forward compatibility.
        argv: object = None
        if len(popen_args) > 1 and isinstance(popen_args[1], (list, tuple)):
            argv = popen_args[1]
        elif popen_args and isinstance(popen_args[0], (list, tuple)):
            argv = popen_args[0]
        if not isinstance(argv, (list, tuple)) or not argv:
            return
        program = os.path.basename(str(argv[0]))
        if program != "git":
            return
        # git runs in the Popen cwd (audited as the third argument): a test
        # that runs git in a temp fixture repo reads the fixture, not the
        # live checkout, and must not be blamed for the checkout's file.
        cwd = popen_args[2] if len(popen_args) > 2 else None
        base: "str | None" = None
        if cwd is not None:
            try:
                base = os.fsdecode(os.fspath(cwd))
            except TypeError:
                base = None
            if base and not os.path.isabs(base):
                base = os.path.join(os.getcwd(), base)
        tokens = [token if isinstance(token, str) else "" for token in argv[1:]]
        # `git -C DIR ...` moves git into DIR before it reads anything.
        while len(tokens) >= 2 and tokens[0] == "-C":
            directory = tokens[1]
            base = directory if os.path.isabs(directory) else os.path.join(base or os.getcwd(), directory)
            tokens = tokens[2:]
        for token in tokens:
            if not token or token.startswith("-"):
                continue
            path = token
            if ":" in path and not path.startswith(":"):
                head, separator, tail = path.partition(":")
                # `git show REV:path` / `git log REV..REV:path`: one prefix, no separator.
                if separator and head and "/" not in head and "\\" not in head and tail:
                    path = tail
            if "/" not in path and os.sep not in path:
                continue
            self._record(path, "git", base)

    # -- the hook ----------------------------------------------------------

    def audit(self, event: str, args: tuple) -> None:
        if self.in_hook:
            return
        self.in_hook = True
        try:
            if event == "open":
                self._record_open(args)
            elif event in ("os.listdir", "os.scandir"):
                self._record(args[0] if args else None, _LIST_KIND)
            elif event == "subprocess.Popen":
                self._record_git(args)
        except Exception:
            pass
        finally:
            self.in_hook = False


def _install_audit_hook() -> None:
    """Add the hook. Called only when this file is loaded as the usercustomize's payload."""

    workspace = os.environ.get("GITHUB_WORKSPACE")
    trace_dir = os.environ.get("ARIA_READ_TRACE_DIR")
    if not workspace or not trace_dir:
        return
    try:
        os.makedirs(trace_dir, exist_ok=True)
    except Exception:
        return
    sys.addaudithook(_TraceState(workspace, trace_dir).audit)


def _cmd_install(trace_dir: "Path") -> int:
    import site
    from pathlib import Path

    trace_dir = trace_dir.resolve()
    user_site = Path(site.getusersitepackages())
    user_site.mkdir(parents=True, exist_ok=True)
    customize = user_site / "usercustomize.py"
    if customize.exists():
        existing = customize.read_text(encoding="utf-8")
        if _MARKER not in existing:
            print(
                f"aria_read_trace: refusing to overwrite a foreign {customize} "
                "(it is not this tracer's usercustomize); remove it or trace manually",
                file=sys.stderr,
            )
            return 1
    customize.write_text(
        _USERCUSTOMIZE.format(hook_path=str(Path(__file__).resolve())), encoding="utf-8"
    )
    github_env = os.environ.get("GITHUB_ENV")
    if github_env:
        with open(github_env, "a", encoding="utf-8") as handle:
            handle.write(f"ARIA_READ_TRACE_DIR={trace_dir}\n")
    print(f"aria_read_trace: hook installed in {customize}; traces under {trace_dir}")
    return 0


def _git(repo: "Path", *args: str) -> "subprocess.CompletedProcess[str]":
    import subprocess

    return subprocess.run(
        ["git", *args], cwd=repo, capture_output=True, text=True, check=False
    )


def _cmd_verify(trace_dir: "Path", manifest_path: "Path") -> int:
    from pathlib import Path

    repo = Path.cwd()
    manifest_file = manifest_path if manifest_path.is_absolute() else repo / manifest_path
    try:
        import json

        manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
        globs = [entry["glob"] for entry in manifest["surface"]]
    except Exception as error:
        print(f"aria_read_trace: unreadable surface manifest {manifest_file}: {error}", file=sys.stderr)
        return 1
    if not globs:
        print(f"aria_read_trace: {manifest_file} declares no surface", file=sys.stderr)
        return 1

    tracked = _git(repo, "ls-files", "-z")
    covered = _git(repo, "ls-files", "-z", "--", *(f":(glob){glob}" for glob in globs))
    if tracked.returncode or covered.returncode:
        print(f"aria_read_trace: git ls-files failed in {repo}", file=sys.stderr)
        return 1
    tracked_set = {path for path in tracked.stdout.split("\0") if path}
    covered_set = {path for path in covered.stdout.split("\0") if path}

    reads: set[str] = set()
    listings: set[str] = set()
    corrupt: list[str] = []
    for trace_file in sorted(Path(trace_dir).glob("trace-*.tsv")):
        try:
            lines = trace_file.read_text(encoding="utf-8").splitlines()
        except Exception as error:
            corrupt.append(f"{trace_file}: unreadable ({error})")
            continue
        for number, line in enumerate(lines, start=1):
            parts = line.split("\t")
            if len(parts) != 2 or not parts[1] or parts[0] not in (*_READ_KINDS, _LIST_KIND):
                corrupt.append(f"{trace_file}:{number}: {line!r}")
                continue
            kind, path = parts[0], _unescape(parts[1])
            if os.path.isabs(path) or path.startswith(".."):
                corrupt.append(f"{trace_file}:{number}: {line!r}")
                continue
            (reads if kind in _READ_KINDS else listings).add(path)

    if corrupt:
        for line in corrupt:
            print(f"aria_read_trace: corrupt trace line: {line}", file=sys.stderr)
        return 1

    uncovered = sorted(path for path in reads if path in tracked_set and path not in covered_set)
    uncovered_tracked = tracked_set - covered_set
    uncovered_prefixes = tuple(f"{path.rpartition('/')[0]}/" for path in uncovered_tracked)
    listed = sorted(
        path for path in listings
        if any(prefix.startswith(f"{path}/") for prefix in uncovered_prefixes)
    )
    if listed:
        print("aria_read_trace: directories listed that hold off-surface tracked files "
              "(reported, not gating; a file read there would fail):")
        for path in listed:
            print(f"  {path}/")
    if uncovered:
        print(
            "aria_read_trace: tracked reads outside the kernel surface "
            "(a PR changing only these skips the job and passes the required check):",
            file=sys.stderr,
        )
        for path in uncovered:
            print(f"  {path}", file=sys.stderr)
        print(
            "  remedy: add a glob naming the reader to "
            f"{manifest_path}, make the test read a fixture under aria-kernel/, "
            "or declare the module READS_LIVE_CHECKOUT",
            file=sys.stderr,
        )
        return 1
    print(
        f"aria_read_trace: {len(reads & tracked_set)} tracked read(s), all on the kernel surface "
        f"({len(listed)} off-surface director(y/ies) listed, reported)"
    )
    return 0


def main(argv: "list[str] | None" = None) -> int:
    import argparse
    from pathlib import Path

    parser = argparse.ArgumentParser(prog="aria_read_trace", description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    install = commands.add_parser("install", help="write the audit hook's usercustomize and arm GITHUB_ENV")
    install.add_argument("--trace-dir", required=True, type=Path)
    verify = commands.add_parser("verify", help="fail on a tracked read outside the surface")
    verify.add_argument("--trace-dir", required=True, type=Path)
    verify.add_argument("--manifest", required=True, type=Path)
    args = parser.parse_args(argv)
    if args.command == "install":
        return _cmd_install(args.trace_dir)
    return _cmd_verify(args.trace_dir, args.manifest)


if __name__ == "__main__":
    raise SystemExit(main())
elif __name__ == _HOOK_MODULE:
    # Loaded by the generated usercustomize: arm the audit hook now, at
    # interpreter startup, when the environment variables are already set.
    _install_audit_hook()
