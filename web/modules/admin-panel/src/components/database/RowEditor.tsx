/**
 * RowEditor Component
 *
 * Enhanced modal for creating and editing database rows.
 * Features smart input types, validation, FK lookups, and grouped field layout.
 */

import React, { useState, useEffect, useCallback, useMemo } from 'react';
import { Modal, Button, Input, Alert, Badge, Spinner } from '@aquaculture/shared-ui';
import { getAccessToken } from '@platform/shared-ui/utils/api-client';

// ============================================================================
// Types
// ============================================================================

export interface ColumnInfo {
  columnName: string;
  dataType: string;
  isNullable: boolean;
  columnDefault: string | null;
  isPrimaryKey: boolean;
  isForeignKey: boolean;
  foreignKeyTable?: string;
  foreignKeyColumn?: string;
}

export interface RowEditorProps {
  isOpen: boolean;
  onClose: () => void;
  schema: string;
  table: string;
  columns: ColumnInfo[];
  row?: Record<string, unknown>; // undefined for create mode
  onSave: (data: Record<string, unknown>) => Promise<void>;
}

interface ForeignKeyOption {
  value: string;
  label: string;
}

interface ValidationError {
  field: string;
  message: string;
}

// ============================================================================
// API Functions
// ============================================================================

const API_BASE = '/api/database/explorer';

const getAuthHeader = (): Record<string, string> => {
  const token = getAccessToken();
  return token ? { Authorization: `Bearer ${token}` } : {};
};

async function fetchForeignKeyValues(
  schema: string,
  table: string,
  column: string,
  search?: string
): Promise<ForeignKeyOption[]> {
  const params = new URLSearchParams({
    limit: '100',
  });
  if (search) {
    params.set('search', search);
  }

  const response = await fetch(
    `${API_BASE}/schemas/${schema}/tables/${table}/columns/${column}/values?${params}`,
    { credentials: 'include', headers: { ...getAuthHeader() } }
  );

  if (!response.ok) {
    // Fallback: try to get data directly from the table
    const dataResponse = await fetch(
      `${API_BASE}/schemas/${schema}/tables/${table}/data?limit=100`,
      { credentials: 'include', headers: { ...getAuthHeader() } }
    );
    if (!dataResponse.ok) return [];

    const data = await dataResponse.json();
    return data.rows.map((row: Record<string, unknown>) => ({
      value: String(row[column] ?? ''),
      label: String(row[column] ?? ''),
    }));
  }

  const json = await response.json();
  return json && json.data ? json.data : json;
}

// ============================================================================
// Utilities
// ============================================================================

const formatValue = (value: unknown): string => {
  if (value === null || value === undefined) return '';
  if (typeof value === 'object') {
    if (value instanceof Date) return value.toISOString();
    return JSON.stringify(value, null, 2);
  }
  return String(value);
};

const formatDateTimeLocal = (value: unknown): string => {
  if (!value) return '';
  const date = new Date(String(value));
  if (isNaN(date.getTime())) return '';
  // Format: YYYY-MM-DDTHH:mm
  return date.toISOString().slice(0, 16);
};

const formatDateValue = (value: unknown): string => {
  if (!value) return '';
  const date = new Date(String(value));
  if (isNaN(date.getTime())) return '';
  // Format: YYYY-MM-DD
  return date.toISOString().slice(0, 10);
};

const isAutoGenerated = (column: ColumnInfo): boolean => {
  const defaultVal = column.columnDefault?.toLowerCase() || '';
  return (
    defaultVal.includes('gen_random_uuid') ||
    defaultVal.includes('uuid_generate') ||
    defaultVal.includes('nextval') ||
    (column.isPrimaryKey && column.dataType.includes('serial'))
  );
};

const isJsonType = (dataType: string): boolean => {
  const type = dataType.toLowerCase();
  return type.includes('json') || type.includes('jsonb');
};

const isNumericType = (dataType: string): boolean => {
  const type = dataType.toLowerCase();
  return (
    type.includes('int') ||
    type.includes('numeric') ||
    type.includes('decimal') ||
    type.includes('float') ||
    type.includes('double') ||
    type.includes('real')
  );
};

const isBooleanType = (dataType: string): boolean => {
  return dataType.toLowerCase().includes('bool');
};

const isDateTimeType = (dataType: string): boolean => {
  const type = dataType.toLowerCase();
  return type.includes('timestamp') || type === 'timestamptz';
};

const isDateType = (dataType: string): boolean => {
  const type = dataType.toLowerCase();
  return type === 'date';
};

const isTextAreaType = (dataType: string): boolean => {
  const type = dataType.toLowerCase();
  return type === 'text' || isJsonType(dataType);
};

const validateJson = (value: string): string | null => {
  if (!value.trim()) return null;
  try {
    JSON.parse(value);
    return null;
  } catch (e) {
    return 'Invalid JSON syntax';
  }
};

const validateNumber = (value: string, dataType: string): string | null => {
  if (!value.trim()) return null;
  const num = Number(value);
  if (isNaN(num)) return 'Must be a valid number';
  if (dataType.toLowerCase().includes('int') && !Number.isInteger(num)) {
    return 'Must be an integer';
  }
  return null;
};

