import { createHash } from 'crypto';

import { BadRequestException } from '@nestjs/common';

import {
  canonicalJsonBytes,
  contractTimestamp,
  type ContractJson,
} from '../edge-device/edge-contract';
import type { OsBundle, UpdateTerms } from '../edge-device/edge-update-manifest.service';
import { parseRecipe, type UpdateRecipe } from '../edge-device/edge-update-recipe';
import type { NetpolicyBody } from '../edge-device/site-netpolicy-manifest.service';

import { EdgeRolloutKind } from './entities/edge-rollout.entity';

/**
 * A rollout's plan (ADR-048 DEC-2.4, DEC-23): what is carried to the cohort (an agent
 * release, an OS bundle, a site config, a site network policy or a trust-anchors bundle),
 * under which terms, in which window, on which devices in which order, and how many
 * failures stop it. The plan is the thing two people approve, so it has one canonical form
 * and one digest ({@link planDigest}); an approval names that digest, and the plan is
 * never edited after it is stored.
 */

/** A rollout is a deliberate cohort, not a fleet-wide broadcast. */
export const MAX_ROLLOUT_DEVICES = 500;
export const MAX_ROLLOUT_WAVES = 10;

/**
 * The operator's extra site files of a site-config rollout are stored with the plan and,
 * as a bundle, with every request of the cohort; this bounds that copy (the contract's own
 * bound is 1 MiB a file).
 */
export const MAX_ROLLOUT_SITE_FILES_BYTES = 262_144;

interface PlanBase {
  /** Null: the window opens when each statement is signed. */
  readonly windowNotBefore: Date | null;
  /** How long each statement stays valid; for a trust-anchors push, how long the cloud keeps delivering it. */
  readonly windowSeconds: number;
  /** The rollout halts when more devices than this fail. */
  readonly maxFailures: number;
  /** Device ids, wave by wave; wave n+1 starts only after wave n concluded. */
  readonly waves: readonly (readonly string[])[];
}

interface TermsPlan extends PlanBase {
  /** The terms root applies the update under. */
  readonly terms: UpdateTerms;
}

/** An agent release for every device of the cohort. */
export interface EdgeRolloutPlan extends TermsPlan {
  readonly kind: EdgeRolloutKind.EDGE_UPDATE;
  readonly version: string;
}

/** An OS bundle for every device of the cohort. */
export interface OsRolloutPlan extends TermsPlan {
  readonly kind: EdgeRolloutKind.OS_UPDATE;
  readonly bundle: OsBundle;
}

/**
 * A site config for every device of the cohort: config.yaml regenerated by the cloud, the
 * RBAC manifest the tenant is on, and the operator's extra site files by path (base64).
 * With no extra file it is how an expiring RBAC manifest is renewed.
 */
export interface SiteConfigRolloutPlan extends PlanBase {
  readonly kind: EdgeRolloutKind.SITE_CONFIG;
  readonly files: Readonly<Record<string, string>>;
}

/** A site network policy for every device of the cohort. */
export interface SiteNetpolicyRolloutPlan extends PlanBase {
  readonly kind: EdgeRolloutKind.SITE_NETPOLICY;
  readonly policy: NetpolicyBody;
}

/** The trust-anchors bundle the cloud holds, by the digest that is approved. */
export interface TrustAnchorsRolloutPlan extends PlanBase {
  readonly kind: EdgeRolloutKind.TRUST_ANCHORS;
  readonly bundleDigest: string;
  readonly bundleSeq: number;
}

export type RolloutPlan =
  | EdgeRolloutPlan
  | OsRolloutPlan
  | SiteConfigRolloutPlan
  | SiteNetpolicyRolloutPlan
  | TrustAnchorsRolloutPlan;

/** Why a plan cannot be a rollout; nothing was stored. */
export class RolloutPlanError extends BadRequestException {
  constructor(detail: string) {
    super(`The rollout plan is not acceptable: ${detail}`);
    this.name = 'RolloutPlanError';
  }
}

/**
 * A JSON-shaped value as the contract's canonical form takes it: an absent optional member
 * is left out, and a number that is not a safe integer is refused (the contract has none).
 */
function contractJson(value: unknown): ContractJson {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return value;
  if (typeof value === 'number') {
    if (!Number.isSafeInteger(value)) {
      throw new RolloutPlanError(`${value} is not an integer the contract can state`);
    }
    return value;
  }
  if (Array.isArray(value)) return value.map(contractJson);
  if (typeof value === 'object') {
    const out: Record<string, ContractJson> = {};
    for (const [key, member] of Object.entries(value)) {
      if (member !== undefined) out[key] = contractJson(member);
    }
    return out;
  }
  throw new RolloutPlanError('it holds a value JSON cannot state');
}

/** What the rollout row stores as `target`, and the digest covers. */
export function targetOf(plan: RolloutPlan): Record<string, ContractJson> {
  switch (plan.kind) {
    case EdgeRolloutKind.EDGE_UPDATE:
      return { version: plan.version };
    case EdgeRolloutKind.OS_UPDATE: {
      const {
        version,
        rollbackFloor,
        minCurrentVersion,
        supportedAgentAbi,
        url,
        sha256,
        sizeBytes,
      } = plan.bundle;
      return {
        bundle: {
          version,
          rollbackFloor,
          minCurrentVersion,
          supportedAgentAbi,
          url,
          sha256,
          sizeBytes,
        },
      };
    }
    case EdgeRolloutKind.SITE_CONFIG:
      return { files: contractJson(plan.files) };
    case EdgeRolloutKind.SITE_NETPOLICY:
      return { policy: contractJson(plan.policy) };
    case EdgeRolloutKind.TRUST_ANCHORS:
      return { bundleDigest: plan.bundleDigest, bundleSeq: plan.bundleSeq };
  }
}

/** What the rollout row stores as `terms`: the terms of an agent or OS update, nothing for the other kinds. */
export function termsOf(plan: RolloutPlan): Record<string, ContractJson> {
  if (plan.kind === EdgeRolloutKind.EDGE_UPDATE || plan.kind === EdgeRolloutKind.OS_UPDATE) {
    return {
      localApproval: plan.terms.localApproval,
      blockersOverride: plan.terms.blockersOverride,
      maxOutageSeconds: plan.terms.maxOutageSeconds,
    };
  }
  return {};
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/** Every device id of the plan, in wave order. */
export function planDevices(plan: RolloutPlan): string[] {
  return plan.waves.flat();
}

/** The structural rules of a plan that need no device, release or bundle to check. */
export function assertPlanShape(plan: RolloutPlan): void {
  if (plan.waves.length < 1 || plan.waves.length > MAX_ROLLOUT_WAVES) {
    throw new RolloutPlanError(
      `it has ${plan.waves.length} waves, between 1 and ${MAX_ROLLOUT_WAVES} are allowed`,
    );
  }
  const seen = new Set<string>();
  for (const [index, wave] of plan.waves.entries()) {
    if (wave.length === 0) throw new RolloutPlanError(`wave ${index + 1} has no device`);
    for (const id of wave) {
      if (!UUID.test(id)) throw new RolloutPlanError(`${id.slice(0, 40)} is not a device id`);
      if (seen.has(id)) throw new RolloutPlanError(`device ${id} is in the cohort twice`);
      seen.add(id);
    }
  }
  if (seen.size > MAX_ROLLOUT_DEVICES) {
    throw new RolloutPlanError(
      `it names ${seen.size} devices, at most ${MAX_ROLLOUT_DEVICES} are allowed`,
    );
  }
  if (!Number.isInteger(plan.maxFailures) || plan.maxFailures < 0 || plan.maxFailures > seen.size) {
    throw new RolloutPlanError(
      `the failure allowance ${plan.maxFailures} is not between 0 and the cohort size`,
    );
  }
  if (plan.windowNotBefore !== null) {
    try {
      contractTimestamp(plan.windowNotBefore);
    } catch (error) {
      throw new RolloutPlanError(
        error instanceof Error ? error.message : 'the window start is invalid',
      );
    }
  }
  if (plan.kind === EdgeRolloutKind.SITE_CONFIG) assertSiteFilesBound(plan.files);
  const recipe = recipeOf({
    kind: plan.kind,
    target: targetOf(plan),
    terms: termsOf(plan),
    windowSeconds: plan.windowSeconds,
  });
  if (recipe === null) {
    throw new RolloutPlanError('its target, terms or window length are not what the kind needs');
  }
}

function assertSiteFilesBound(files: Readonly<Record<string, string>>): void {
  const bytes = Object.values(files).reduce(
    (sum, content) => sum + Buffer.from(content, 'base64').length,
    0,
  );
  if (bytes > MAX_ROLLOUT_SITE_FILES_BYTES) {
    throw new RolloutPlanError(
      `its site files are ${bytes} bytes, at most ${MAX_ROLLOUT_SITE_FILES_BYTES} are allowed`,
    );
  }
}

/**
 * What re-issues every statement of the rollout: the stored target, terms and
 * window length, read through the one parser that admits a recipe. Null when the
 * target does not fit its kind.
 */
export function recipeOf(stored: {
  readonly kind: string;
  readonly target: object;
  readonly terms: object;
  readonly windowSeconds: number;
}): UpdateRecipe | null {
  return parseRecipe({
    kind: stored.kind,
    ...stored.target,
    terms: stored.terms,
    windowSeconds: stored.windowSeconds,
  });
}

/**
 * The digest of the canonical plan: sorted members, whole-second window start,
 * the devices of each wave in sorted order (a wave is a set). It is what an
 * approval confirms and what the rollout row stores.
 */
export function planDigest(plan: RolloutPlan): string {
  const canonical: ContractJson = {
    version: 1,
    kind: plan.kind,
    target: targetOf(plan),
    terms: termsOf(plan),
    window_not_before:
      plan.windowNotBefore === null ? null : contractTimestamp(plan.windowNotBefore),
    window_seconds: plan.windowSeconds,
    max_failures: plan.maxFailures,
    waves: plan.waves.map((wave) => [...wave].sort()),
  };
  return createHash('sha256').update(canonicalJsonBytes(canonical)).digest('hex');
}
