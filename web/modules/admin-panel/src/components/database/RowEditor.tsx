interface FieldInputProps {
  column: ColumnInfo;
  value: string;
  onChange: (value: string) => void;
  disabled: boolean;
  error?: string;
  fkOptions: ForeignKeyOption[];
  fkLoading: boolean;
  fkSearch: string;
  onFkSearch: (search: string) => void;
}

const FieldInput: React.FC<FieldInputProps> = ({
  column,
  value,
  onChange,
  disabled,
  error,
  fkOptions,
  fkLoading,
  fkSearch,
  onFkSearch,
}) => {
  const inputClassName = `w-full px-3 py-2 border rounded-lg transition-colors text-sm
    ${error ? 'border-red-500 focus:ring-red-500' : 'border-gray-300 focus:ring-blue-500'}
    ${disabled ? 'bg-gray-100 cursor-not-allowed text-gray-500' : 'bg-white'}
    focus:outline-none focus:ring-2`;

  // Foreign Key Select
  if (column.isForeignKey && !disabled) {
    return (
      <div className="relative">
        <div className="flex gap-2">
          <input
            type="text"
            value={fkSearch}
            onChange={(e) => onFkSearch(e.target.value)}
            placeholder="Search..."
            className="flex-1 px-3 py-2 border border-gray-300 rounded-lg text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"
          />
        </div>
        <select
          value={value}
          onChange={(e) => onChange(e.target.value)}
          disabled={disabled}
          className={`${inputClassName} mt-2`}
        >
          <option value="">-- Select --</option>
          {fkLoading ? (
            <option disabled>Loading...</option>
          ) : (
            fkOptions.map((opt) => (
              <option key={opt.value} value={opt.value}>
                {opt.label}
              </option>
            ))
          )}
        </select>
        <div className="text-xs text-gray-500 mt-1">
          FK: {column.foreignKeyTable}.{column.foreignKeyColumn}
        </div>
      </div>
    );
  }

  // Boolean Checkbox
  if (isBooleanType(column.dataType)) {
    return (
      <label className="flex items-center gap-3 cursor-pointer">
        <input
          type="checkbox"
          checked={value === 'true' || value === '1'}
          onChange={(e) => onChange(e.target.checked ? 'true' : 'false')}
          disabled={disabled}
          className="w-5 h-5 rounded border-gray-300 text-blue-600 focus:ring-blue-500 cursor-pointer disabled:cursor-not-allowed"
        />
        <span className="text-sm text-gray-600">
          {value === 'true' || value === '1' ? 'True' : 'False'}
        </span>
      </label>
    );
  }

  // DateTime Local
  if (isDateTimeType(column.dataType)) {
    return (
      <input
        type="datetime-local"
        value={formatDateTimeLocal(value) || value}
        onChange={(e) => onChange(e.target.value)}
        disabled={disabled}
        className={inputClassName}
      />
    );
  }

  // Date
  if (isDateType(column.dataType)) {
    return (
      <input
        type="date"
        value={formatDateValue(value) || value}
        onChange={(e) => onChange(e.target.value)}
        disabled={disabled}
        className={inputClassName}
      />
    );
  }

  // Number
  if (isNumericType(column.dataType)) {
    return (
      <input
        type="number"
        value={value}
        onChange={(e) => onChange(e.target.value)}
        disabled={disabled}
        step={column.dataType.toLowerCase().includes('int') ? '1' : 'any'}
        className={inputClassName}
      />
    );
  }

  // Textarea (JSON or text)
  if (isTextAreaType(column.dataType)) {
    return (
      <textarea
        value={value}
        onChange={(e) => onChange(e.target.value)}
        disabled={disabled}
        rows={isJsonType(column.dataType) ? 5 : 3}
        className={`${inputClassName} font-mono`}
        placeholder={isJsonType(column.dataType) ? '{ }' : ''}
      />
    );
  }

  // Default: Text input
  return (
    <input
      type="text"
      value={value}
      onChange={(e) => onChange(e.target.value)}
      disabled={disabled}
      className={inputClassName}
      placeholder={column.columnDefault || ''}
    />
  );
};

