export const RowEditor: React.FC<RowEditorProps> = ({
  isOpen,
  onClose,
  schema,
  table,
  columns,
  row,
  onSave,
}) => {
  const isEditMode = row !== undefined;

  // Form state
  const [formData, setFormData] = useState<Record<string, string>>({});
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [validationErrors, setValidationErrors] = useState<ValidationError[]>([]);

  // FK state
  const [fkOptions, setFkOptions] = useState<Record<string, ForeignKeyOption[]>>({});
  const [fkLoading, setFkLoading] = useState<Record<string, boolean>>({});
  const [fkSearch, setFkSearch] = useState<Record<string, string>>({});

  // Group columns
  const { primaryKeyColumns, requiredColumns, optionalColumns } = useMemo(() => {
    const pkCols: ColumnInfo[] = [];
    const reqCols: ColumnInfo[] = [];
    const optCols: ColumnInfo[] = [];

    columns.forEach((col) => {
      if (col.isPrimaryKey) {
        pkCols.push(col);
      } else if (!col.isNullable && !col.columnDefault) {
        reqCols.push(col);
      } else {
        optCols.push(col);
      }
    });

    return {
      primaryKeyColumns: pkCols,
      requiredColumns: reqCols,
      optionalColumns: optCols,
    };
  }, [columns]);

  // Initialize form data
  useEffect(() => {
    if (isOpen) {
      const initialData: Record<string, string> = {};
      columns.forEach((col) => {
        if (row && row[col.columnName] !== undefined && row[col.columnName] !== null) {
          if (isBooleanType(col.dataType)) {
            initialData[col.columnName] = row[col.columnName] ? 'true' : 'false';
          } else if (isDateTimeType(col.dataType)) {
            initialData[col.columnName] = formatDateTimeLocal(row[col.columnName]);
          } else if (isDateType(col.dataType)) {
            initialData[col.columnName] = formatDateValue(row[col.columnName]);
          } else {
            initialData[col.columnName] = formatValue(row[col.columnName]);
          }
        } else {
          initialData[col.columnName] = '';
        }
      });
      setFormData(initialData);
      setError(null);
      setValidationErrors([]);
      setFkSearch({});
    }
  }, [isOpen, columns, row]);

  // Load FK options
  useEffect(() => {
    if (!isOpen) return;

    const fkColumns = columns.filter((col) => col.isForeignKey && col.foreignKeyTable && col.foreignKeyColumn);

    fkColumns.forEach((col) => {
      loadFkOptions(col.columnName, col.foreignKeyTable!, col.foreignKeyColumn!, '');
    });
  }, [isOpen, columns, schema]);

  const loadFkOptions = useCallback(
    async (columnName: string, fkTable: string, fkColumn: string, search: string) => {
      setFkLoading((prev) => ({ ...prev, [columnName]: true }));

      try {
        const options = await fetchForeignKeyValues(schema, fkTable, fkColumn, search);
        setFkOptions((prev) => ({ ...prev, [columnName]: options }));
      } catch {
        setFkOptions((prev) => ({ ...prev, [columnName]: [] }));
      } finally {
        setFkLoading((prev) => ({ ...prev, [columnName]: false }));
      }
    },
    [schema]
  );

  const handleFkSearch = useCallback(
    (columnName: string, col: ColumnInfo, search: string) => {
      setFkSearch((prev) => ({ ...prev, [columnName]: search }));

      // Debounce search
      const timeoutId = setTimeout(() => {
        if (col.foreignKeyTable && col.foreignKeyColumn) {
          loadFkOptions(columnName, col.foreignKeyTable, col.foreignKeyColumn, search);
        }
      }, 300);

      return () => clearTimeout(timeoutId);
    },
    [loadFkOptions]
  );

  const handleFieldChange = useCallback((columnName: string, value: string) => {
    setFormData((prev) => ({ ...prev, [columnName]: value }));
    // Clear validation error for this field
    setValidationErrors((prev) => prev.filter((e) => e.field !== columnName));
  }, []);

  const validateForm = useCallback((): boolean => {
    const errors: ValidationError[] = [];

    columns.forEach((col) => {
      const value = formData[col.columnName]?.trim() || '';
      const isAutoGen = isAutoGenerated(col);

      // Skip auto-generated fields in create mode
      if (!isEditMode && isAutoGen) return;

      // Required field validation
      if (!col.isNullable && !col.columnDefault && !isAutoGen && !value) {
        errors.push({ field: col.columnName, message: 'This field is required' });
        return;
      }

      if (!value) return;

      // Type-specific validation
      if (isJsonType(col.dataType)) {
        const jsonError = validateJson(value);
        if (jsonError) {
          errors.push({ field: col.columnName, message: jsonError });
        }
      }

      if (isNumericType(col.dataType)) {
        const numError = validateNumber(value, col.dataType);
        if (numError) {
          errors.push({ field: col.columnName, message: numError });
        }
      }
    });

    setValidationErrors(errors);
    return errors.length === 0;
  }, [columns, formData, isEditMode]);

  const handleSave = async () => {
    if (!validateForm()) return;

    setSaving(true);
    setError(null);

    try {
      const parsedData: Record<string, unknown> = {};

      columns.forEach((col) => {
        const value = formData[col.columnName];
        const isAutoGen = isAutoGenerated(col);

        // Skip auto-generated fields in create mode
        if (!isEditMode && isAutoGen) return;

        // Skip primary key in edit mode if auto-generated
        if (isEditMode && col.isPrimaryKey && isAutoGen) return;

        if (value === '' || value === undefined) {
          if (col.isNullable) {
            parsedData[col.columnName] = null;
          }
          return;
        }

        // Parse based on data type
        if (isBooleanType(col.dataType)) {
          parsedData[col.columnName] = value === 'true' || value === '1';
        } else if (isNumericType(col.dataType)) {
          parsedData[col.columnName] = col.dataType.toLowerCase().includes('int')
            ? parseInt(value, 10)
            : parseFloat(value);
        } else if (isJsonType(col.dataType)) {
          try {
            parsedData[col.columnName] = JSON.parse(value);
          } catch {
            parsedData[col.columnName] = value;
          }
        } else if (isDateTimeType(col.dataType) || isDateType(col.dataType)) {
          parsedData[col.columnName] = value ? new Date(value).toISOString() : null;
        } else {
          parsedData[col.columnName] = value;
        }
      });

      await onSave(parsedData);
      onClose();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to save');
    } finally {
      setSaving(false);
    }
  };

  const handleReset = () => {
    const initialData: Record<string, string> = {};
    columns.forEach((col) => {
      if (row && row[col.columnName] !== undefined && row[col.columnName] !== null) {
        if (isBooleanType(col.dataType)) {
          initialData[col.columnName] = row[col.columnName] ? 'true' : 'false';
        } else if (isDateTimeType(col.dataType)) {
          initialData[col.columnName] = formatDateTimeLocal(row[col.columnName]);
        } else if (isDateType(col.dataType)) {
          initialData[col.columnName] = formatDateValue(row[col.columnName]);
        } else {
          initialData[col.columnName] = formatValue(row[col.columnName]);
        }
      } else {
        initialData[col.columnName] = '';
      }
    });
    setFormData(initialData);
    setValidationErrors([]);
    setError(null);
  };

  const getFieldError = (columnName: string): string | undefined => {
    return validationErrors.find((e) => e.field === columnName)?.message;
  };

  const renderColumnField = (col: ColumnInfo) => {
    const isAutoGen = isAutoGenerated(col);
    const isDisabled = isAutoGen && (isEditMode || !isEditMode); // Disabled in both modes for auto-gen
    const fieldError = getFieldError(col.columnName);
    const isRequired = !col.isNullable && !col.columnDefault && !isAutoGen;

    return (
      <div key={col.columnName} className="space-y-1">
        {/* Label */}
        <label className="flex items-center gap-2 text-sm font-medium text-gray-700">
          <span>{col.columnName}</span>
          {col.isPrimaryKey && (
            <Badge variant="info" className="text-xs">
              PK
            </Badge>
          )}
          {col.isForeignKey && (
            <Badge variant="warning" className="text-xs">
              FK
            </Badge>
          )}
          {isRequired && <span className="text-red-500">*</span>}
        </label>

        {/* Input */}
        <FieldInput
          column={col}
          value={formData[col.columnName] || ''}
          onChange={(value) => handleFieldChange(col.columnName, value)}
          disabled={isDisabled}
          error={fieldError}
          fkOptions={fkOptions[col.columnName] || []}
          fkLoading={fkLoading[col.columnName] || false}
          fkSearch={fkSearch[col.columnName] || ''}
          onFkSearch={(search) => handleFkSearch(col.columnName, col, search)}
        />

        {/* Field info & error */}
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <Badge
              variant={
                isNumericType(col.dataType)
                  ? 'info'
                  : isBooleanType(col.dataType)
                  ? 'error'
                  : isDateTimeType(col.dataType) || isDateType(col.dataType)
                  ? 'warning'
                  : 'default'
              }
              className="text-xs"
            >
              {col.dataType}
            </Badge>
            {col.isNullable && (
              <span className="text-xs text-gray-400">nullable</span>
            )}
            {isAutoGen && (
              <span className="text-xs text-gray-400">auto-generated</span>
            )}
          </div>
          {fieldError && (
            <span className="text-xs text-red-500">{fieldError}</span>
          )}
        </div>
      </div>
    );
  };

  const renderFieldGroup = (
    title: string,
    cols: ColumnInfo[],
    variant: 'primary' | 'required' | 'optional'
  ) => {
    if (cols.length === 0) return null;

    const bgColor =
      variant === 'primary'
        ? 'bg-blue-50 border-blue-200'
        : variant === 'required'
        ? 'bg-yellow-50 border-yellow-200'
        : 'bg-gray-50 border-gray-200';

    return (
      <div className={`p-4 rounded-lg border ${bgColor}`}>
        <h4 className="text-sm font-semibold text-gray-700 mb-4">{title}</h4>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {cols.map(renderColumnField)}
        </div>
      </div>
    );
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={isEditMode ? `Edit Row - ${table}` : `Add New Row - ${table}`}
      description={`Schema: ${schema}`}
      size="xl"
    >
      {/* Error Alert */}
      {error && (
        <Alert type="error" className="mb-4" dismissible onDismiss={() => setError(null)}>
          {error}
        </Alert>
      )}

      {/* Validation Errors Summary */}
      {validationErrors.length > 0 && (
        <Alert type="warning" className="mb-4">
          <span className="font-medium">Please fix the following errors:</span>
          <ul className="mt-2 list-disc list-inside">
            {validationErrors.map((err) => (
              <li key={err.field}>
                <span className="font-medium">{err.field}:</span> {err.message}
              </li>
            ))}
          </ul>
        </Alert>
      )}

      {/* Scrollable Content */}
      <div className="space-y-6 max-h-[60vh] overflow-y-auto pr-2">
        {/* Primary Keys */}
        {renderFieldGroup('Primary Keys', primaryKeyColumns, 'primary')}

        {/* Required Fields */}
        {renderFieldGroup('Required Fields', requiredColumns, 'required')}

        {/* Optional Fields */}
        {renderFieldGroup('Optional Fields', optionalColumns, 'optional')}
      </div>

      {/* Actions */}
      <div className="flex items-center justify-between mt-6 pt-4 border-t border-gray-200">
        <Button
          variant="ghost"
          onClick={handleReset}
          disabled={saving}
        >
          Reset Form
        </Button>

        <div className="flex gap-3">
          <Button
            variant="outline"
            onClick={onClose}
            disabled={saving}
          >
            Cancel
          </Button>
          <Button
            onClick={handleSave}
            disabled={saving}
          >
            {saving ? (
              <>
                <Spinner size="sm" className="mr-2" />
                Saving...
              </>
            ) : isEditMode ? (
              'Save Changes'
            ) : (
              'Create Row'
            )}
          </Button>
        </div>
      </div>
    </Modal>
  );
};

export default RowEditor;
