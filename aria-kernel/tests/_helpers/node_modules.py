"""The checkout's own installed node packages, for fixtures that run nx/tsc.

WHY (ARIA-MEDIUM-134): three end-to-end fixtures symlinked
``/var/aqua-saas/node_modules`` — the operator host's main checkout — into
their throwaway repositories. That path exists on exactly one machine, so
the suite was green on the droplet and red on every other host, including
the kernel CI lane, where ``npm ci`` had installed the very same packages
under the checkout being tested. A fixture's dependencies come from the
checkout the suite runs in; nothing else is portable.

``installed_node_modules`` names the missing package when the checkout has
no install (``npm ci`` not run) instead of failing later inside nx with an
unrelated error.
"""
from __future__ import annotations

from pathlib import Path

# aria-kernel/tests/_helpers/node_modules.py → the repository root.
REPO_ROOT = Path(__file__).resolve().parents[3]


def installed_node_modules(*packages: str) -> Path:
    """The checkout's ``node_modules`` (resolved through a worktree's symlink),
    after checking every named package is installed there."""
    installed = (REPO_ROOT / "node_modules").resolve()
    missing = [name for name in packages if not (installed / name / "package.json").is_file()]
    if missing:
        raise AssertionError(
            f"node_modules_missing:{','.join(missing)} under {installed} — run `npm ci` in the checkout"
        )
    return installed
