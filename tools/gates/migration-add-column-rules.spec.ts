#!/usr/bin/env ts-node
/**
 * ADR-053 — the two migration-sql-lint rules that govern `ADD COLUMN`:
 *
 *   R13-add-column-rewriting-default  (per chunk) an ADD that rewrites or scans
 *                                     a table it does not create, and any
 *                                     CREATE DOMAIN;
 *   R14-add-column-exemption-shape    (per file) a migration that uses the
 *                                     catalog-only NOT NULL DEFAULT exemption
 *                                     must have the Decision-3 shape.
 *
 * Every case goes through the gate's public entry points (`scanMigrationSql`
 * for bare SQL, `inspectMigrationSource` for a TypeORM migration), the ones the
 * CLI and ARIA's sql-migration-safety-adapter call.
 */

import { strict as assert } from 'node:assert';
import { test } from 'node:test';

import {
  MIGRATION_SQL_LINT_RULE_IDS,
  inspectMigrationSource,
  scanMigrationSql,
  type Violation,
} from './migration-sql-lint';

const R13 = 'R13-add-column-rewriting-default';
const R14 = 'R14-add-column-exemption-shape';
const MIGRATION_PATH = 'apps/farm-service/src/database/migrations/1900000000000-AddSiteModule.ts';

function ruleHits(violations: readonly Violation[], ruleId: string): readonly Violation[] {
  return violations.filter((violation) => violation.ruleId === ruleId);
}

function expectR13(sql: string, expectedCount: number): void {
  const hits = ruleHits(scanMigrationSql(sql), R13);
  assert.strictEqual(hits.length, expectedCount, `${sql}\n${JSON.stringify(hits)}`);
}

/** A TypeORM migration whose up()/down() bodies are the given lines. */
function migration(up: readonly string[], down: readonly string[], members = ''): string {
  return [
    "import { MigrationInterface, QueryRunner } from 'typeorm';",
    '',
    'export class AddSiteModule1900000000000 implements MigrationInterface {',
    ...(members === '' ? [] : [`  ${members}`, '']),
    '  public async up(queryRunner: QueryRunner): Promise<void> {',
    ...up.map((line) => `    ${line}`),
    '  }',
    '',
    '  public async down(queryRunner: QueryRunner): Promise<void> {',
    ...down.map((line) => `    ${line}`),
    '  }',
    '}',
    '',
  ].join('\n');
}

const SET_TIMEOUT = "await queryRunner.query(`SET LOCAL lock_timeout = '2s'`);";
const ADD_SITE_MODULE = [
  'await queryRunner.query(`',
  '  -- ADR-053: every site that exists before this release belongs to the farm module',
  '  ALTER TABLE sites ADD COLUMN IF NOT EXISTS module farm_registry_module_enum',
  "    NOT NULL DEFAULT 'farm'::farm_registry_module_enum",
  '`);',
];
const DROP_SITE_MODULE =
  'await queryRunner.query(`ALTER TABLE sites DROP COLUMN IF EXISTS module`);';
const COMPLIANT = migration([SET_TIMEOUT, ...ADD_SITE_MODULE], [SET_TIMEOUT, DROP_SITE_MODULE]);

function r14(source: string): readonly Violation[] {
  return ruleHits(inspectMigrationSource(MIGRATION_PATH, source), R14);
}

/** The requirement letters (a)-(e) of the R14 hits, sorted, each hit HIGH. */
function r14Requirements(source: string): readonly string[] {
  const hits = r14(source);
  for (const hit of hits) assert.strictEqual(hit.severity, 'HIGH');
  return hits.map((hit) => /^\(([a-e])\)/.exec(hit.message)?.[1] ?? `?${hit.message}`).sort();
}

function expectR14(source: string, requirements: readonly string[]): void {
  assert.deepStrictEqual(r14Requirements(source), [...requirements].sort(), source);
}

// --- the rule registry ------------------------------------------------------

void test('the gate reports both ADR-053 rules', () => {
  assert.ok(MIGRATION_SQL_LINT_RULE_IDS.includes(R13));
  assert.ok(MIGRATION_SQL_LINT_RULE_IDS.includes(R14));
});

// --- R13: rewriting defaults ------------------------------------------------

void test('R13 flags each volatile default on a table the chunk does not create', () => {
  for (const definition of [
    'id uuid NOT NULL DEFAULT gen_random_uuid()',
    'id uuid NOT NULL DEFAULT uuid_generate_v4()',
    'seen_at timestamptz NOT NULL DEFAULT clock_timestamp()',
    'jitter double precision DEFAULT random()',
    "seq bigint NOT NULL DEFAULT nextval('sites_seq')",
  ]) {
    expectR13(`ALTER TABLE sites ADD COLUMN IF NOT EXISTS ${definition};`, 1);
  }
});

void test('R13 flags serial, identity and GENERATED … STORED columns', () => {
  for (const definition of [
    'seq bigserial',
    'seq serial4',
    'seq bigint GENERATED ALWAYS AS IDENTITY',
    'seq bigint GENERATED BY DEFAULT AS IDENTITY',
    'doubled integer GENERATED ALWAYS AS (qty * 2) STORED',
  ]) {
    expectR13(`ALTER TABLE sites ADD COLUMN IF NOT EXISTS ${definition};`, 1);
  }
});

void test('R13 counts an interpolated DEFAULT as outside the allowlist', () => {
  expectR13('ALTER TABLE sites ADD COLUMN IF NOT EXISTS module text NOT NULL DEFAULT ${value};', 1);
});

void test('R13 flags NOT NULL DEFAULT with an inline constraint, which scans the table', () => {
  for (const constraint of ['CHECK (qty >= 0)', 'REFERENCES farms(id)', 'UNIQUE', 'PRIMARY KEY']) {
    expectR13(
      `ALTER TABLE sites ADD COLUMN IF NOT EXISTS qty integer NOT NULL DEFAULT 0 ${constraint};`,
      1,
    );
  }
});

void test('R13 flags every CREATE DOMAIN', () => {
  expectR13('CREATE DOMAIN positive_qty AS integer CHECK (VALUE > 0);', 1);
});

void test('R13 passes every ADR-053 Decision-1 default and a plain nullable add', () => {
  for (const definition of [
    "module farm_registry_module_enum NOT NULL DEFAULT 'farm'::farm_registry_module_enum",
    'module farm_registry_module_enum NOT NULL DEFAULT \'farm\'::"farm"."farm_registry_module_enum"',
    'qty integer NOT NULL DEFAULT 0',
    'delta integer NOT NULL DEFAULT -1',
    'active boolean NOT NULL DEFAULT false',
    "meta jsonb NOT NULL DEFAULT '{}'::jsonb",
    "tags text[] NOT NULL DEFAULT '{}'::text[]",
    "code character varying(20) NOT NULL DEFAULT 'x'::character varying(20)",
    'amount numeric(10,2) NOT NULL DEFAULT 0',
    'registered_at timestamptz NOT NULL DEFAULT now()',
    'registered_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP',
    'registered_on date NOT NULL DEFAULT CURRENT_DATE',
    'note text DEFAULT NULL',
    'note text',
    'farm_id uuid REFERENCES farms(id)',
  ]) {
    expectR13(`ALTER TABLE sites ADD COLUMN IF NOT EXISTS ${definition};`, 0);
  }
});

void test('R13 exempts a table the same chunk creates (it is empty)', () => {
  expectR13(
    `CREATE TABLE IF NOT EXISTS "sites" (name text);
     ALTER TABLE sites ADD COLUMN IF NOT EXISTS id uuid NOT NULL DEFAULT gen_random_uuid();`,
    0,
  );
});

void test('R13 judges each ADD of a multi-action ALTER TABLE on its own', () => {
  expectR13(
    `ALTER TABLE sites
       ADD COLUMN IF NOT EXISTS qty numeric(10,2) NOT NULL DEFAULT 0,
       ADD COLUMN IF NOT EXISTS ref uuid DEFAULT gen_random_uuid();`,
    1,
  );
});

void test('R13 reads an ADD inside a DO block', () => {
  expectR13(
    `DO $$ BEGIN
       ALTER TABLE sites ADD COLUMN IF NOT EXISTS id uuid NOT NULL DEFAULT gen_random_uuid();
     END $$;`,
    1,
  );
});

void test('R13 ignores ADD COLUMN text inside a string literal', () => {
  expectR13(
    "COMMENT ON TABLE sites IS 'ALTER TABLE sites ADD COLUMN id uuid DEFAULT gen_random_uuid()';",
    0,
  );
});

// --- R14: the exemption's shape --------------------------------------------

void test('R14 passes the Decision-3 shape, and the whole gate is clean on it', () => {
  assert.deepStrictEqual(inspectMigrationSource(MIGRATION_PATH, COMPLIANT), []);
});

void test('R14 accepts read-only SELECT probes and other SET LOCAL statements', () => {
  const source = migration(
    [
      "await queryRunner.query(`SET LOCAL lock_timeout = '1500ms'`);",
      'await queryRunner.query(`SET LOCAL statement_timeout = 60000`);',
      "await queryRunner.query(`SELECT 1 FROM information_schema.columns WHERE table_name = 'sites'`);",
      ...ADD_SITE_MODULE,
    ],
    ['await queryRunner.query(`SET LOCAL lock_timeout = 2000`);', DROP_SITE_MODULE],
  );
  assert.deepStrictEqual(r14(source), []);
});

void test('R14 does not apply to a file without a Decision-1 ADD', () => {
  const source = migration(
    [
      'await queryRunner.query(`ALTER TABLE sites ADD COLUMN IF NOT EXISTS note text`);',
      "await queryRunner.query(`UPDATE sites SET note = 'x'`);",
    ],
    [DROP_SITE_MODULE],
  );
  assert.deepStrictEqual(r14(source), []);
});

void test('R14 does not apply to a table the same file creates', () => {
  const source = migration(
    [
      'await queryRunner.query(`CREATE TABLE IF NOT EXISTS sites (id uuid)`);',
      'await queryRunner.query(`ALTER TABLE sites ADD COLUMN IF NOT EXISTS qty integer NOT NULL DEFAULT 0`);',
      'await queryRunner.query(`CREATE INDEX IF NOT EXISTS sites_qty_idx ON sites (qty)`);',
    ],
    ['await queryRunner.query(`DROP TABLE IF EXISTS sites -- DESTRUCTIVE: re-run up()`);'],
  );
  assert.deepStrictEqual(r14(source), []);
});

void test('R14 (a) requires the ADR-053 reason in the same statement', () => {
  const unmarked = ADD_SITE_MODULE.filter((line) => !line.includes('ADR-053'));
  expectR14(migration([SET_TIMEOUT, ...unmarked], [SET_TIMEOUT, DROP_SITE_MODULE]), ['a']);

  const markerOnAnotherStatement = migration(
    [
      "await queryRunner.query(`SET LOCAL lock_timeout = '2s'; -- ADR-053: wrong statement`);",
      ...unmarked,
    ],
    [SET_TIMEOUT, DROP_SITE_MODULE],
  );
  expectR14(markerOnAnotherStatement, ['a']);

  const emptyReason = migration(
    [SET_TIMEOUT, ...ADD_SITE_MODULE.map((line) => line.replace(/ADR-053:.*/, 'ADR-053:'))],
    [SET_TIMEOUT, DROP_SITE_MODULE],
  );
  expectR14(emptyReason, ['a']);
});

void test('R14 (a) points at the ADD it judges', () => {
  const unmarked = ADD_SITE_MODULE.filter((line) => !line.includes('ADR-053'));
  const source = migration([SET_TIMEOUT, ...unmarked], [SET_TIMEOUT, DROP_SITE_MODULE]);
  const [hit] = r14(source);
  const addLine = source.split('\n').findIndex((line) => line.includes('ADD COLUMN')) + 1;
  assert.strictEqual(hit?.line, addLine);
});

void test('a // comment above the ADD does not shift the reported line', () => {
  const unmarked = ADD_SITE_MODULE.filter((line) => !line.includes('ADR-053'));
  const source = migration(
    [SET_TIMEOUT, '// the farm module owns every legacy site', ...unmarked],
    [SET_TIMEOUT, DROP_SITE_MODULE],
  );
  const [hit] = r14(source);
  assert.ok(hit);
  const addLine = source.split('\n').findIndex((line) => line.includes('ADD COLUMN')) + 1;
  assert.strictEqual(hit.line, addLine);
  assert.ok(hit.message.startsWith('(a)'), hit.message);
});

void test('R14 (b) requires SET LOCAL lock_timeout <= 2s before the first ALTER TABLE of up()', () => {
  expectR14(migration([...ADD_SITE_MODULE], [SET_TIMEOUT, DROP_SITE_MODULE]), ['b']);
  expectR14(migration([...ADD_SITE_MODULE, SET_TIMEOUT], [SET_TIMEOUT, DROP_SITE_MODULE]), ['b']);
  expectR14(
    migration(
      ["await queryRunner.query(`SET lock_timeout = '2s'`);", ...ADD_SITE_MODULE],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    ),
    // A session-scoped SET is no bound for this transaction, and it is not a
    // statement the exemption allows.
    ['b', 'd'],
  );
});

void test('R14 (b) requires the same bound before the first ALTER TABLE of down()', () => {
  expectR14(migration([SET_TIMEOUT, ...ADD_SITE_MODULE], [DROP_SITE_MODULE]), ['b']);
});

void test('R14 (b) rejects a larger, zero or unreadable lock_timeout anywhere in the file', () => {
  for (const value of ["'3s'", "'2001ms'", '0', "'0'", "'1min'", 'DEFAULT']) {
    const source = migration(
      [
        SET_TIMEOUT,
        ...ADD_SITE_MODULE,
        `await queryRunner.query(\`SET LOCAL lock_timeout = ${value}\`);`,
      ],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    );
    expectR14(source, ['b']);
  }
  // An interpolated value is unreadable, and so is the statement that holds it.
  expectR14(
    migration(
      [
        SET_TIMEOUT,
        ...ADD_SITE_MODULE,
        "await queryRunner.query(`SET LOCAL lock_timeout = '${timeout}'`);",
      ],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    ),
    ['b', 'd'],
  );
  const viaSetConfig = migration(
    [
      SET_TIMEOUT,
      ...ADD_SITE_MODULE,
      "await queryRunner.query(`SELECT set_config('lock_timeout', '30s', true)`);",
    ],
    [SET_TIMEOUT, DROP_SITE_MODULE],
  );
  expectR14(viaSetConfig, ['b']);
});

void test('R14 (b) rejects an ALTER TABLE outside up() and down()', () => {
  const source = migration(
    [SET_TIMEOUT, 'await this.addModule(queryRunner);'],
    [SET_TIMEOUT, DROP_SITE_MODULE],
    [
      'private async addModule(queryRunner: QueryRunner): Promise<void> {',
      ...ADD_SITE_MODULE,
      '}',
    ].join('\n  '),
  );
  expectR14(source, ['b']);
});

void test('R14 (c) requires every ALTER TABLE to name the same literal table', () => {
  expectR14(
    migration(
      [
        SET_TIMEOUT,
        ...ADD_SITE_MODULE,
        'await queryRunner.query(`ALTER TABLE farms ADD COLUMN IF NOT EXISTS note text`);',
      ],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    ),
    ['c'],
  );
  expectR14(
    migration(
      [
        SET_TIMEOUT,
        ...ADD_SITE_MODULE.map((line) => line.replace('TABLE sites', 'TABLE ${table}')),
      ],
      [SET_TIMEOUT, DROP_SITE_MODULE.replace('TABLE sites', 'TABLE ${table}')],
    ),
    ['c', 'c'],
  );
});

void test('R14 (d) rejects any statement outside SET LOCAL, SELECT, ADD and the inverse DROP', () => {
  for (const statement of [
    "UPDATE sites SET name = 'x'",
    'CREATE INDEX IF NOT EXISTS sites_module_idx ON sites (module)',
    'ALTER TABLE sites ALTER COLUMN name SET NOT NULL',
    'ALTER TABLE sites ADD CONSTRAINT sites_name_key UNIQUE (name)',
    'SELECT id INTO TEMP copy FROM sites',
    'SELECT id FROM sites FOR UPDATE',
    'DO $$ BEGIN PERFORM 1; END $$',
    'RESET lock_timeout',
  ]) {
    const source = migration(
      [SET_TIMEOUT, ...ADD_SITE_MODULE, `await queryRunner.query(\`${statement}\`);`],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    );
    const requirements = r14Requirements(source);
    assert.ok(requirements.length >= 1, statement);
    assert.ok(
      requirements.every((requirement) => requirement === 'd'),
      `${statement}: ${requirements.join(',')}`,
    );
  }
});

void test('R14 (d) allows DROP COLUMN only as the inverse of an added column, in down()', () => {
  expectR14(
    migration(
      [SET_TIMEOUT, ...ADD_SITE_MODULE],
      [SET_TIMEOUT, 'await queryRunner.query(`ALTER TABLE sites DROP COLUMN IF EXISTS name`);'],
    ),
    ['d'],
  );
  expectR14(
    migration([SET_TIMEOUT, ...ADD_SITE_MODULE, DROP_SITE_MODULE], [SET_TIMEOUT, DROP_SITE_MODULE]),
    ['d'],
  );
});

void test('R14 (d) rejects a query whose SQL the gate cannot read', () => {
  expectR14(
    migration(
      [SET_TIMEOUT, ...ADD_SITE_MODULE, "await queryRunner.query('SELECT 1');"],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    ),
    ['d'],
  );
});

void test('R14 (e) rejects transaction = false and withDdlSafety', () => {
  expectR14(
    migration(
      [SET_TIMEOUT, ...ADD_SITE_MODULE],
      [SET_TIMEOUT, DROP_SITE_MODULE],
      'public readonly transaction = false;',
    ),
    ['e'],
  );
  expectR14(
    migration(
      [
        'await withDdlSafety(queryRunner, { lockTimeoutMs: 2000 }, async () => {',
        SET_TIMEOUT,
        ...ADD_SITE_MODULE,
        '});',
      ],
      [SET_TIMEOUT, DROP_SITE_MODULE],
    ),
    ['e'],
  );
});

void test('R14 judges a bare .sql migration as one body', () => {
  const sql = [
    "SET LOCAL lock_timeout = '2s';",
    '-- ADR-053: every site that exists before this release belongs to the farm module',
    'ALTER TABLE sites ADD COLUMN IF NOT EXISTS qty integer NOT NULL DEFAULT 0;',
  ].join('\n');
  assert.deepStrictEqual(scanMigrationSql(sql), []);
  assert.strictEqual(
    ruleHits(scanMigrationSql(sql.split('\n').slice(1).join('\n')), R14).length,
    1,
  );
});
