import { MigrationInterface, QueryRunner } from 'typeorm';

/**
 * A second broker-credential slot, so re-provisioning never replaces the credential a
 * running agent holds before the reinstalled one has proved its own (SENSOR-MEDIUM-236;
 * ADR-048 DEC-5.7, DEC-5.14).
 *
 * # Why
 *
 * `edge_devices.mqtt_password_hash` was the device's only broker credential. Activation
 * during a re-provisioning window wrote the new hash over it while the activation was still
 * uncommitted (the token is spent only when the device's own credential authenticates a
 * CONNECT), so a reinstall that failed, was rolled back or never reached the broker left the
 * previously working agent unable to authenticate.
 *
 * `previous_mqtt_password_hash` holds the credential of the last COMMITTED activation while
 * an activation issued over it is not committed. The activation moves the committed hash
 * there in the statement that writes the new one; the commit retires it in the statement
 * that spends the token; a new window drops the uncommitted credential and restores it. The
 * check makes any other row unrepresentable: a previous credential exists only beside a
 * current one, under an unspent token, with credentials issued.
 *
 * # Tenant routing
 *
 * `edge_devices` is per-tenant. Unqualified identifiers: db-migrate runs this once per
 * schema (the source `sensor` schema and every `tenant_*`) with the search_path pinned.
 *
 * # Blue-green
 *
 * Nullable column, no backfill, no destructive change. A row mid-activation when this ships
 * is an ordinary first activation (its hash is the credential the pending commit needs, the
 * previous slot is empty), so the new service commits it exactly as the old one did. The
 * check admits every row the old service writes except a commit that leaves a previous
 * credential behind, which the old service never creates. `down` drops the column: a device
 * whose reinstall is in flight loses the running credential it kept, which is the state this
 * migration exists to prevent and which `down` states.
 *
 * Generated by TypeORM's schema builder (the entity as it is now against the entity as it
 * was); the add of the check sits in the duplicate_object guard the migration gate requires
 * (PG has no IF NOT EXISTS for ADD CONSTRAINT).
 */
export class EdgeDeviceCredentialSlot1834000000000 implements MigrationInterface {
  name = 'EdgeDeviceCredentialSlot1834000000000';

  public async up(queryRunner: QueryRunner): Promise<void> {
    await queryRunner.query(
      `ALTER TABLE "edge_devices" ADD COLUMN IF NOT EXISTS "previous_mqtt_password_hash" character varying(128)`,
    );
    await queryRunner.query(`
      DO $$ BEGIN
        ALTER TABLE "edge_devices" ADD CONSTRAINT "CHK_edge_devices_previous_credential" CHECK (("previous_mqtt_password_hash" IS NULL) OR ("mqtt_password_hash" IS NOT NULL AND "token_used_at" IS NULL AND "credentials_issued_at" IS NOT NULL));
      EXCEPTION WHEN duplicate_object THEN NULL;
      END $$;
    `);
  }

  public async down(queryRunner: QueryRunner): Promise<void> {
    await queryRunner.query(
      `ALTER TABLE "edge_devices" DROP CONSTRAINT IF EXISTS "CHK_edge_devices_previous_credential"`,
    );
    await queryRunner.query(
      `ALTER TABLE "edge_devices" DROP COLUMN IF EXISTS "previous_mqtt_password_hash"`,
    );
  }
}
